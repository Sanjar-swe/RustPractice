// Отлично! Переходим к одной из самых важных и уникальных концепций Rust — Задаче 5: Владение (Ownership).
//
// Система владения — это набор правил, которые компилятор Rust проверяет во время компиляции. Эти правила позволяют Rust обеспечивать безопасность памяти (отсутствие гонок данных, висячих указателей, двойного освобождения) без необходимости сборщика мусора (GC), как в Python или Go.
//
///Основные правила владения:

// Каждое значение в Rust имеет переменную, которая называется его владельцем (owner).
// В каждый момент времени у значения может быть только один владелец.
// Когда владелец выходит из области видимости (scope), значение удаляется (dropped).

fn main() {
    // s недоступна здесь, она еще не объявлена
    {
        let s = String::from("hello"); // s доступна с этого момента
                                       // работаем с s
        println!("{}", s);
    } // область видимости s заканчивается здесь.
      // s больше не доступна. Rust автоматически вызывает `drop` для `String`,
      // освобождая память в куче.
      // println!("{}", s); // Ошибка компиляции! s больше не существует.
}
